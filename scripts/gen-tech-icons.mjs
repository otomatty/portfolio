// 技術スタックのバッジ用の SVG スプライト（public/icons/tech.svg）を作る。
// src/data/tech-icons.ts を変えたら `bun run gen:tech-icons` で作り直す。
//
// - Simple Icons（CC0）は公式の色で描く。カードの背景との比が 3:1 未満の色（黒など）は、
//   バッジの文字色（currentColor）で描く
// - public/icons の SVG（Cloudflare Docs のアイコン、CC BY 4.0）は、元の色のまま使う
import { readFileSync, writeFileSync } from 'node:fs';
import * as simpleIcons from 'simple-icons';
import { TECH_ICONS, techIconId } from '../src/data/tech-icons.ts';

const OUTPUT = new URL('../public/icons/tech.svg', import.meta.url);

/** カードの背景（--card: 136 31% 10%）。ロゴの色との比が MIN_CONTRAST 未満なら文字色で描く */
const BACKGROUND = { h: 136, s: 31, l: 10 };
const MIN_CONTRAST = 3;

const bySlug = new Map(
  Object.values(simpleIcons)
    .filter((icon) => icon && typeof icon === 'object' && 'slug' in icon)
    .map((icon) => [icon.slug, icon])
);

const hslToRgb = ({ h, s, l }) => {
  const a = (s / 100) * Math.min(l / 100, 1 - l / 100);
  const f = (n) => {
    const k = (n + h / 30) % 12;
    return l / 100 - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
  };
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
};

const hexToRgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));

const luminance = (rgb) => {
  const [r, g, b] = rgb.map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const background = hslToRgb(BACKGROUND);

const fromSimpleIcons = (id, slug) => {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons に ${slug} がありません`);
  const fill = contrast(hexToRgb(icon.hex), background) >= MIN_CONTRAST ? `#${icon.hex}` : 'currentColor';
  return {
    symbol: `<symbol id="${id}" viewBox="0 0 24 24"><path fill="${fill}" d="${icon.path}"/></symbol>`,
    license: icon.license ? `${icon.title}: ${icon.license.type}${icon.license.url ? ` (${icon.license.url})` : ''}` : null,
  };
};

const fromFile = (id, file) => {
  const svg = readFileSync(new URL(`../public/icons/${file}`, import.meta.url), 'utf8').trim();
  const open = svg.match(/^<svg\b([^>]*)>/);
  if (!open) throw new Error(`${file} の <svg> が読めません`);
  const viewBox = open[1].match(/\bviewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${file} に viewBox がありません`);
  // viewBox・寸法・名前空間以外のルートの属性（fill など）は <g> に移して引き継ぐ
  const attrs = open[1].replace(/\s(xmlns(:\w+)?|viewBox|width|height)="[^"]*"/g, '').trim();
  const inner = svg.slice(open[0].length, svg.lastIndexOf('</svg>')).trim();
  return { symbol: `<symbol id="${id}" viewBox="${viewBox}"><g${attrs ? ` ${attrs}` : ''}>${inner}</g></symbol>`, license: null };
};

const symbols = new Map();
const licenses = new Set();
for (const source of Object.values(TECH_ICONS)) {
  const id = techIconId(source);
  if (symbols.has(id)) continue;
  const built = 'simpleIcons' in source ? fromSimpleIcons(id, source.simpleIcons) : fromFile(id, source.file);
  symbols.set(id, built.symbol);
  if (built.license) licenses.add(built.license);
}

const header = [
  'Generated by scripts/gen-tech-icons.mjs from src/data/tech-icons.ts. Do not edit by hand.',
  'Logos are trademarks of their respective owners, used only to name the technologies used.',
  'Simple Icons (https://simpleicons.org): CC0-1.0. Icons with their own license:',
  ...[...licenses].sort().map((line) => `  ${line}`),
  'Cloudflare product icons: cloudflare/cloudflare-docs (CC BY 4.0), recolored.',
].join('\n');

const body = [...symbols]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([, symbol]) => symbol)
  .join('\n');

writeFileSync(OUTPUT, `<svg xmlns="http://www.w3.org/2000/svg">\n<!--\n${header}\n-->\n${body}\n</svg>\n`);
console.log(`wrote ${symbols.size} icons to public/icons/tech.svg`);
